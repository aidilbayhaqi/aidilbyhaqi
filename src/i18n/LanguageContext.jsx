const translateDeep = (value, language) => {
  if (language !== "id") return value;
  if (typeof value === "string") return idPhrases[value] || value;
  if (Array.isArray(value)) return value.map((item) => translateDeep(item, language));
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, translateDeep(item, language)]));
  }
  return value;
};

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState(() => {
    const saved = window.localStorage.getItem("portfolio-language");
    if (saved === "id" || saved === "en") return saved;
    return navigator.language?.toLowerCase().startsWith("id") ? "id" : "en";
  });

  useEffect(() => {
    window.localStorage.setItem("portfolio-language", language);
    document.documentElement.lang = language;
    document.title = language === "id"
      ? "Muhammad Aidil Bayhaqi — Fullstack Developer & System Builder"
      : "Muhammad Aidil Bayhaqi — Fullstack Developer & System Builder";
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    toggleLanguage: () => setLanguage((current) => (current === "id" ? "en" : "id")),
    t: (key) => ui[language][key] || ui.en[key] || key,
    translateData: (data) => translateDeep(data, language),
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
};
